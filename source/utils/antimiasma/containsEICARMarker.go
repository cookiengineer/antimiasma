package antimiasma

import "strings"

var decoded_eicar string

// Original string with every byte shifted by +13.
// See https://en.wikipedia.org/wiki/EICAR_test_file
var shifted_eicar = []byte{
	0x65, 0x42, 0x5c, 0x2e, 0x5d, 0x32, 0x4d, 0x4e,
	0x5d, 0x68, 0x41, 0x69, 0x5d, 0x67, 0x65, 0x42,
	0x41, 0x35, 0x5d, 0x6b, 0x36, 0x44, 0x50, 0x50,
	0x36, 0x44, 0x8a, 0x31, 0x52, 0x56, 0x50, 0x4e,
	0x5f, 0x3a, 0x60, 0x61, 0x4e, 0x5b, 0x51, 0x4e,
	0x5f, 0x51, 0x3a, 0x4e, 0x5b, 0x61, 0x56, 0x63,
	0x56, 0x5f, 0x62, 0x60, 0x3a, 0x61, 0x52, 0x60,
	0x61, 0x3a, 0x53, 0x56, 0x59, 0x52, 0x2e, 0x31,
	0x55, 0x38, 0x55, 0x37,
}

func init() {

	decoded := make([]byte, len(shifted_eicar))

	for i, b := range shifted_eicar {
		decoded[i] = b - 13
	}

	decoded_eicar = string(decoded)

}

func containsEICARMarker(content string) bool {

	return strings.Contains(content, decoded_eicar)

}
